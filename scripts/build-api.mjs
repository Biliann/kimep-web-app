// Bundles server/chat.ts (and the shared src/ data it uses) into one self-contained file
// that Vercel runs as a Node function: api/chat.js. Run automatically by `npm run build`.
import { build } from "esbuild";
await build({
  entryPoints: ["server/chat.ts"],
  outfile: "api/chat.js",
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  banner: { js: "// GENERATED by scripts/build-api.mjs from server/ and src/. Do not edit by hand." },
  logLevel: "info",
});
